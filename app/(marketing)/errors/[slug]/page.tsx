import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { SectionHead } from "@/components/landing";
import { CompetitorLinks } from "@/components/marketing/competitor";
import { CtaBand } from "@/components/marketing/cta-band";
import { Band, Bullets, PageHero } from "@/components/marketing/sections";
import { formatMonth } from "@/components/marketing/updated-at";
import { ERROR_GROUPS, ERRORS, getError } from "@/content/errors";
import { CHECK_LABEL, runProbe } from "@/lib/error-probes";
import { pageMetadata } from "@/lib/seo";
import { relatedLinks } from "@/lib/seo-links";

// Fully prerendered from content/errors.ts; unknown errors are real 404s (see alternatives/[slug]).
export const instant = false;

export function generateStaticParams() {
  return ERRORS.map((e) => ({ slug: e.slug }));
}

export async function generateMetadata({ params }: PageProps<"/errors/[slug]">): Promise<Metadata> {
  const e = getError((await params).slug);
  return e ? pageMetadata(e.seo) : {};
}

const OUTCOME = { success: "Passes", failure: "Fails", inconclusive: "Inconclusive" } as const;

export default async function ErrorPage({ params }: PageProps<"/errors/[slug]">) {
  const e = getError((await params).slug);
  if (!e) notFound();
  const group = ERROR_GROUPS.find((g) => g.id === e.group)!;
  const results = e.probes.map((p) => runProbe(p.probe));

  return (
    <>
      <PageHero
        crumbs={[
          { name: "Errors", path: "/errors" },
          { name: e.code, path: e.seo.path },
        ]}
        kicker={group.title}
        title={e.code}
      >
        <p className="m-0 text-[19px] leading-snug font-semibold">{e.name}</p>
        <p className="m-0 text-[16px] leading-relaxed text-ink-2">{e.meaning}</p>
        {e.aliases.length ? (
          <p className="m-0 text-[14px] text-ink-2">
            Also shown as: <span className="break-words">{e.aliases.join(" · ")}</span>
          </p>
        ) : null}
        <p className="m-0 text-[12.5px] text-muted">
          Checked against browser source code, specifications and vendor docs as of{" "}
          <time dateTime={e.verifiedAt}>{formatMonth(e.verifiedAt)}</time>. <a href="#sources">Sources</a>
        </p>
      </PageHero>

      <Band>
        <SectionHead kicker="What visitors see" title="How it looks to your client’s visitors" />
        <p className="m-0 max-w-[760px] text-[15px] leading-relaxed text-ink-2">{e.visitor}</p>
      </Band>

      <Band tinted>
        <SectionHead kicker="Causes" title="Likely causes, most likely first" />
        <ol className="m-0 flex max-w-[760px] list-none flex-col gap-4 p-0">
          {e.causes.map((c, i) => (
            <li key={c.title} className="flex gap-4">
              <span aria-hidden="true" className="font-mono text-[13px] text-muted">
                {String(i + 1).padStart(2, "0")}
              </span>
              <div className="flex flex-col gap-1">
                <h3 className="m-0 text-[16px] font-semibold">{c.title}</h3>
                <p className="m-0 text-[14.5px] leading-relaxed text-ink-2">{c.text}</p>
              </div>
            </li>
          ))}
        </ol>
      </Band>

      <Band>
        <SectionHead kicker="Fix" title="How to fix it as the agency" />
        <Bullets items={e.fixes} />
      </Band>

      <Band tinted>
        <SectionHead kicker="In Client Status" title="How Client Status classifies it" intro={e.clientStatus} />
        <div className="flex max-w-[860px] flex-col gap-2">
          <ul className="m-0 flex list-none flex-col border-t border-rule p-0">
            {results.map((r, i) => (
              <li key={i} className="grid gap-1 border-b border-rule py-4 tbl:grid-cols-[150px_1fr] tbl:gap-x-6">
                <div className="flex flex-col gap-0.5">
                  <span className="text-[14px] font-semibold">{CHECK_LABEL[r.check]}</span>
                  <span className="font-mono text-[12px] text-muted uppercase">{OUTCOME[r.status]}</span>
                </div>
                <div className="flex flex-col gap-1">
                  <code className="w-fit font-mono text-[13px] break-words">{r.summary}</code>
                  <span className="text-[14px] leading-relaxed text-ink-2">{r.effect}</span>
                </div>
              </li>
            ))}
          </ul>
          <p className="m-0 text-[12.5px] text-muted">
            Generated by running Client Status’s own classification code on a simulated response; response times and
            dates are examples.
          </p>
        </div>
      </Band>

      <Band>
        <SectionHead kicker="Related" title="Tools and related errors" />
        <CompetitorLinks items={relatedLinks({ kind: "error", slug: e.slug })} />
        <div id="sources" className="flex scroll-mt-20 flex-col gap-2 text-[13px]">
          <h2 className="m-0 text-[15px] font-semibold">Sources</h2>
          <ul className="m-0 flex list-none flex-col gap-1 p-0">
            {e.sources.map((u) => (
              <li key={u}>
                <a href={u} rel="nofollow noopener" target="_blank" className="break-all">
                  {u}
                </a>
              </li>
            ))}
          </ul>
        </div>
      </Band>

      <CtaBand />
    </>
  );
}
